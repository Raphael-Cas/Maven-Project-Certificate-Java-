package com.biblioteca.repository;

import com.biblioteca.entity.Livro;
import com.biblioteca.persistence.DatabaseException;
import com.biblioteca.persistence.EntityManagerProvider;
import jakarta.persistence.EntityManager;
import jakarta.persistence.EntityTransaction;
import jakarta.persistence.PersistenceException;

import java.util.List;
import java.util.Optional;
import java.util.function.Function;

/**
 * All communication with the "livro" table lives here (CRUD).
 * Every method opens its own EntityManager through EntityManagerProvider and closes it
 * automatically with try-with-resources. Database failures are reported to the caller as a
 * DatabaseException (it replaces SQLException), which decides how to report it to the user.
 *
 * No SQL is written by hand: Hibernate generates the INSERT / SELECT / UPDATE / DELETE
 * statements from the mapping of the Livro entity.
 */
public class LivroRepository {

    private static final String SELECT_ALL = "SELECT l FROM Livro l ORDER BY l.id";

    /** Inserts a book and stores the id generated by the database in the given object. */
    public void insert(Livro livro) {
        inTransaction(em -> {
            // With GenerationType.IDENTITY Hibernate runs the INSERT right away
            // and fills the generated id into the object.
            em.persist(livro);
            return null;
        });
    }

    /** Returns every book, ordered by id. */
    public List<Livro> findAll() {
        return query(em -> em.createQuery(SELECT_ALL, Livro.class).getResultList());
    }

    /** Returns the book with the given id, or an empty Optional if it does not exist. */
    public Optional<Livro> findById(int id) {
        return query(em -> Optional.ofNullable(em.find(Livro.class, id)));
    }

    /** Updates all editable fields of a book. Returns true if a row was changed. */
    public boolean update(Livro livro) {
        return inTransaction(em -> {
            if (em.find(Livro.class, livro.getId()) == null) {
                return false;
            }
            // The object received here is detached (its EntityManager is already closed):
            // merge copies its state into the managed row, and the UPDATE runs on commit.
            em.merge(livro);
            return true;
        });
    }

    /** Deletes a book by id. Returns true if a row was removed. */
    public boolean delete(int id) {
        return inTransaction(em -> {
            Livro livro = em.find(Livro.class, id);
            if (livro == null) {
                return false;
            }
            // The DELETE runs on commit. If the book still has loans, PostgreSQL refuses it
            // (foreign key violation) and the failure is reported as a DatabaseException.
            em.remove(livro);
            return true;
        });
    }

    // Runs a read-only operation with its own short-lived EntityManager (no transaction needed).
    private <T> T query(Function<EntityManager, T> operation) {
        try (EntityManager em = EntityManagerProvider.getEntityManager()) {
            return operation.apply(em);
        } catch (PersistenceException e) {
            throw DatabaseException.from(e);
        }
    }

    // Runs an operation that changes data inside a transaction:
    // commit when it succeeds, rollback when anything fails.
    private <T> T inTransaction(Function<EntityManager, T> operation) {
        try (EntityManager em = EntityManagerProvider.getEntityManager()) {
            EntityTransaction transaction = em.getTransaction();
            try {
                transaction.begin();
                T result = operation.apply(em);
                transaction.commit();
                return result;
            } catch (RuntimeException e) {
                if (transaction.isActive()) {
                    transaction.rollback();
                }
                throw e;
            }
        } catch (PersistenceException e) {
            throw DatabaseException.from(e);
        }
    }
}
